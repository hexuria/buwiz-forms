function matrixRowsToPath(rows: readonly string[]): string {
  return rows.map((row, y) => {
    if (row.length !== 120 || /[^01]/u.test(row)) {
      throw new Error("1702-MX official PDF417 matrix must be 120 binary modules wide");
    }
    const commands: string[] = [];
    let start = -1;
    for (let x = 0; x <= row.length; x += 1) {
      const black = x < row.length && row[x] === "1";
      if (black && start < 0) start = x;
      if (!black && start >= 0) {
        const width = x - start;
        commands.push(`M${start} ${y}h${width}v1h-${width}z`);
        start = -1;
      }
    }
    return commands.join("");
  }).join("");
}

