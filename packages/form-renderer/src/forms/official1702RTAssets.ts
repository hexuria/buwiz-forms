function pathFromMatrix(rows: readonly string[]): string {
  let path = "";
  for (const [y, row] of rows.entries()) {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "0") {
        x += 1;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "1") x += 1;
      path += `M${start} ${y}h${x - start}v1H${start}z`;
    }
  }
  return path;
}

