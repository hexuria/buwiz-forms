/// Forms filed once per transaction or event: nothing on them carries.
pub const ONE_OFF_FORMS: &[&str] = &[
    "1606", "1706", "1707", "1707A", "1800", "1801", "2000OT", "2552", "2553", "2200A", "2200AN",
    "2200C", "2200M", "2200P", "2200S", "2200T",
];

/// Items the app leaves unanswered on a new return on purpose, so the user
/// answers them each time: 1601C Items 3 (Any Taxes Withheld?) and 11
/// (Category of Withholding Agent), 2551Q Item 13 (the 8% choice).
pub const LEFT_OPEN: &[(&str, &str)] = &[("1601C", "3"), ("1601C", "11"), ("2551Q", "13")];

/// Draft fields the profile's tax facts fill on a new return (decisions 4,
/// 9 and 11): the profile wins for them, so they never carry. Matched by
/// the last segment of the path.
pub const FACT_FIELDS: &[&str] = &[
    "line_of_business",
    "taxpayer_classification",
    "eopt_tier",
    "withholding_agent_category",
    "business_start_date",
    "taxpayer_type",
    "tax_classification",
];

/// Forms whose own ATC answer is filled from the profile's usual ATC codes
/// (`/atc`): the profile wins for it.
const ATC_FROM_PROFILE: &[&str] = &["1701Q", "1701"];

/// The 8% markers of an income-tax rate choice.
const EIGHT_PERCENT: &[&str] = &["EightPercent", "eight_percent", "Ii015", "Ii017"];

/// Why a box carries or not.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Carry {
    /// Copied into a new return.
    Carries,
    /// Not an answer of its own: not a box, a hidden control, a row family
    /// pattern, one radio of an item, or a box nothing on the page writes.
    NotAnAnswer,
    Computed,
    /// A profile or identity box, or one writing a profile box's field.
    Locked,
    /// An income-tax election: only the user answers it, each year.
    Election,
    /// A tax fact the profile holds ([`FACT_FIELDS`]).
    Fact,
    /// On a one-off transaction form.
    OneOff,
    Penalty,
    Amount,
    Date,
    /// A period or event box.
    Period,
    /// The "Amended Return?" answer.
    Amended,
    /// Left open on purpose ([`LEFT_OPEN`]).
    LeftOpen,
    /// A schedule row's own entry (a name, a number, a description): that
    /// period's, not an answer to start from.
    RowEntry,
}

impl Carry {
    /// Filled last period but not copied: an automatic stop.
    pub fn is_auto_stop(self) -> bool {
        matches!(self, Self::Amount | Self::Date)
    }
}

/// One package's page-side carry inputs (`data/agent-carry.json`).
#[derive(Debug, Default, Deserialize)]
struct PageCarry {
    #[serde(default)]
    computed: BTreeSet<String>,
    #[serde(default)]
    money: BTreeSet<String>,
    #[serde(default)]
    dates: BTreeSet<String>,
    #[serde(default)]
    period: BTreeSet<String>,
    #[serde(default)]
    page_writes: BTreeSet<String>,
}

fn page_carry(package: &str) -> &'static PageCarry {
    static PARSED: OnceLock<BTreeMap<String, PageCarry>> = OnceLock::new();
    static EMPTY: OnceLock<PageCarry> = OnceLock::new();
    PARSED
        .get_or_init(|| {
            serde_json::from_str(include_str!("../../../data/agent-carry.json"))
                .expect("data/agent-carry.json parses")
        })
        .get(package)
        .unwrap_or_else(|| EMPTY.get_or_init(PageCarry::default))
}

/// The bindings an answer writes through: its own, or its radios'.
fn bindings_of<'a>(def: &'a AgentFormDef, entry: &'a BoxDef) -> Vec<&'a super::BoundBox> {
    let mut bound: Vec<&super::BoundBox> = def.bindings.get(&entry.key).into_iter().collect();
    if entry.radio_group {
        bound.extend(entry.members.iter().filter_map(|key| def.bindings.get(key)));
    }
    bound
}

/// The draft fields the profile boxes write.
fn profile_paths(kind: AgentFormKind) -> &'static BTreeSet<String> {
    static PATHS: OnceLock<BTreeMap<&'static str, BTreeSet<String>>> = OnceLock::new();
    static EMPTY: BTreeSet<String> = BTreeSet::new();
    PATHS
        .get_or_init(|| {
            AgentFormKind::all()
                .into_iter()
                .map(|kind| {
                    let def = kind.definition();
                    let paths = def
                        .boxes
                        .iter()
                        .filter(|entry| is_profile_box(def, entry))
                        .flat_map(|entry| {
                            let group = entry
                                .group
                                .as_deref()
                                .and_then(|group| def.bindings.get(group));
                            def.bindings.get(&entry.key).into_iter().chain(group)
                        })
                        .flat_map(|bound| binding_paths(&bound.binding))
                        .map(str::to_string)
                        .collect();
                    (kind.package(), paths)
                })
                .collect()
        })
        .get(kind.package())
        .unwrap_or(&EMPTY)
}

/// A "Category of Withholding Agent" (private or government) answer: the
/// profile's government withholding entity fact, however the form names
/// the box.
fn is_agent_category(key: &str, label: &str) -> bool {
    let name = key.rsplit(':').next().unwrap_or(key).to_ascii_lowercase();
    let name = if name.len() <= 2 {
        // `frm0619E:optCategory:P`: the radio's own last segment is its value.
        key.to_ascii_lowercase()
    } else {
        name
    };
    let category = ["category", "ctgry", "catagent"]
        .iter()
        .any(|word| name.contains(word));
    let agent = ["agent", "agnt", "optcategory"]
        .iter()
        .any(|word| name.contains(word));
    (category && agent) || label.contains("category of withholding agent")
}

fn leaf(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Why `key` of `kind` carries or not.
pub fn carry_of(kind: AgentFormKind, key: &str) -> Carry {
    let def = kind.definition();
    let code = kind.form_code();
    let page = page_carry(kind.package());
    let Some(entry) = def.box_def(key) else {
        return Carry::NotAnAnswer;
    };
    if entry.group.is_none()
        && (entry.computed || entry.required == "computed" || page.computed.contains(key))
    {
        return Carry::Computed;
    }
    if !entry.is_question() {
        return Carry::NotAnAnswer;
    }
    let bound = bindings_of(def, entry);
    let keys: Vec<&str> = std::iter::once(key)
        .chain(entry.members.iter().map(String::as_str))
        .collect();
    let members = || keys.iter().filter_map(|key| def.box_def(key));
    if members().any(|entry| entry.computed || entry.required == "computed")
        || keys.iter().any(|key| page.computed.contains(*key))
    {
        return Carry::Computed;
    }
    let host = keys
        .iter()
        .any(|key| host_writes(kind, key) || page.page_writes.contains(*key));
    if bound.is_empty() && !host {
        return Carry::NotAnAnswer;
    }
    let paths: Vec<&str> = bound
        .iter()
        .flat_map(|bound| binding_paths(&bound.binding))
        .collect();
    let profile = profile_paths(kind);
    if bound
        .iter()
        .any(|bound| matches!(bound.lock, Some(Lock::Profile | Lock::Identity)))
        || members().any(|entry| is_profile_box(def, entry))
        || paths.iter().any(|path| profile.contains(*path))
    {
        return Carry::Locked;
    }
    let label = entry.label.to_ascii_lowercase();
    let eight_percent = bound.iter().any(|bound| match &bound.binding {
        Binding::Choice { options } => options.iter().any(|option| {
            option.set.values().any(|value| {
                value
                    .as_str()
                    .is_some_and(|value| EIGHT_PERCENT.contains(&value))
            })
        }),
        _ => false,
    });
    if bound.iter().any(|bound| bound.lock == Some(Lock::Election))
        || paths.iter().any(|path| {
            let leaf = leaf(path);
            leaf.contains("election")
                || leaf == "tax_rate"
                || leaf == "tax_option"
                || (leaf.ends_with("deduction_method") && code.starts_with("1701"))
        })
        || (label.contains("tax rate")
            && (eight_percent || label.contains("8%") || label.contains("graduated")))
    {
        return Carry::Election;
    }
    if paths.iter().any(|path| {
        FACT_FIELDS.contains(&leaf(path)) || (*path == "/atc" && ATC_FROM_PROFILE.contains(&code))
    }) || is_agent_category(key, &label)
    {
        return Carry::Fact;
    }
    if ONE_OFF_FORMS.contains(&code) {
        return Carry::OneOff;
    }
    if penalties::groups(kind)
        .iter()
        .any(|group| group.keys.iter().any(|k| k == key))
        || penalties::override_of(kind, key).is_some()
    {
        return Carry::Penalty;
    }
    let amount = bound.iter().any(|bound| match &bound.binding {
        Binding::Amount { .. } => true,
        Binding::Whole { .. } => page.money.contains(key),
        _ => false,
    }) || (bound.is_empty() && page.money.contains(key));
    if amount {
        return Carry::Amount;
    }
    let date = bound
        .iter()
        .any(|bound| matches!(&bound.binding, Binding::Text { date: Some(_), .. }))
        || page.dates.contains(key);
    if date {
        return Carry::Date;
    }
    if page.period.contains(key)
        || paths.iter().any(|path| {
            PERIOD_FIELDS.contains(&leaf(path))
                || leaf(path).starts_with("is_short_period")
                || crate::forms::event_trigger::trigger_field_of(code, path).is_some()
        })
    {
        return Carry::Period;
    }
    if paths.iter().any(|path| leaf(path).contains("amend")) || label.contains("amended return") {
        return Carry::Amended;
    }
    if LEFT_OPEN
        .iter()
        .any(|(form, item)| *form == code && entry.item == *item)
    {
        return Carry::LeftOpen;
    }
    // A schedule row's cell (its path goes through a row index), or a cell
    // the page's host writes with no field of its own: only a code pick.
    let in_row = paths.iter().any(|path| {
        path.split('/')
            .any(|segment| !segment.is_empty() && segment.chars().all(|c| c.is_ascii_digit()))
    });
    let code_pick = key.to_ascii_lowercase().contains("atc")
        || label.contains("atc")
        || entry.kind.contains("select")
        || entry.is_radio()
        || entry.kind.contains("checkbox")
        || bound
            .iter()
            .any(|bound| matches!(bound.binding, Binding::Choice { .. }));
    if (in_row || bound.is_empty()) && !code_pick {
        return Carry::RowEntry;
    }
    Carry::Carries
}

/// Whether box `key` of `kind` is copied into a new return.
pub fn carries(kind: AgentFormKind, key: &str) -> bool {
    carry_of(kind, key) == Carry::Carries
}

/// Every box of `kind` that carries, in the form's order.
pub fn carried_boxes(kind: AgentFormKind) -> Vec<&'static str> {
    kind.definition()
        .boxes
        .iter()
        .map(|entry| entry.key.as_str())
        .filter(|key| carries(kind, key))
        .collect()
}

/// The boxes that may carry a "Stop here" switch: the user's own answers
/// (not computed, not a profile or identity box), in the form's order.
pub fn stoppable(kind: AgentFormKind) -> Vec<&'static str> {
    kind.definition()
        .boxes
        .iter()
        .map(|entry| entry.key.as_str())
        .filter(|key| is_stoppable(kind, key))
        .collect()
}

pub fn is_stoppable(kind: AgentFormKind, key: &str) -> bool {
    !matches!(
        carry_of(kind, key),
        Carry::NotAnAnswer | Carry::Computed | Carry::Locked
    )
}

/// The answer `key` names: its radio item's group box, or itself.
pub fn answer_key(kind: AgentFormKind, key: &str) -> String {
    kind.definition().question_of(key)
}

/// The boxes the form page draws for the answer `key`: a radio item's group
/// box is drawn as its radios, each under its own key; any other box is
/// itself. The page looks boxes up by the keys it draws, so what it is told
/// about an answer (copied, a stop, switchable) is told for each of these.
pub fn page_keys(kind: AgentFormKind, key: &str) -> Vec<String> {
    match kind.definition().box_def(key) {
        Some(entry) if entry.radio_group && !entry.members.is_empty() => entry.members.clone(),
        _ => vec![key.to_string()],
    }
}

/// A value that counts as not filled: no text, `false`, or zero.
pub fn is_blank_value(value: &str) -> bool {
    let value = value.trim();
    value.is_empty()
        || value == "false"
        || super::parse_amount(value).is_some_and(|amount| amount == 0.0)
}

