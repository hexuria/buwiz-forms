//! The carry rule (owner's decisions 9 and 10): which boxes a new return
//! copies from the previous period's return of its form, or from the
//! branch's template. One rule for every form.
//!
//! A box carries only when it is an answer the user types or picks on the
//! page (bound to the draft, or written by the page's host editors such as
//! 2551Q's ATC selects) and it is none of these:
//!
//! - computed (the package's flag or the page schema's `c`; either counts);
//! - locked: a profile, identity or income-tax election box (the 8% or
//!   graduated choice and its deduction method, however the form asks it),
//!   or a box that writes a draft field a profile box writes;
//! - a tax fact the profile holds ([`FACT_FIELDS`]): the profile fills it;
//! - on a one-off transaction form ([`ONE_OFF_FORMS`]);
//! - a penalty or another amount (an `amount` binding, a `whole` binding or
//!   a host-written cell the page draws as money);
//! - a date (a `date` binding or a box the page draws as a date);
//! - a period or event box (a field of [`super::PERIOD_FIELDS`], an event
//!   trigger field);
//! - the "Amended Return?" answer;
//! - an answer the app leaves open on purpose ([`LEFT_OPEN`]).
//!
//! An ATC row's code carries; its amounts do not (they are amounts). Of a
//! schedule's other row cells (a payee's name, a receipt number, a bank
//! code) nothing carries: they are that period's entries. A code pick (an
//! ATC, a select, a radio) carries.
//!
//! A radio item is one answer: its group box carries, its radios are not
//! boxes of their own here. The page's schema names a radio's group box in
//! its `grp`.
//!
//! What core cannot read (the page schema's `c` flag and the page's money
//! and date types) is pinned in `data/agent-carry.json`, generated by
//! bir-shell's `agent_carry_table` test.

