//! The per-form print fixes (`print-overrides/<slug>.css`) as a table compiled into the library, for Android.
//!
//! A desktop package keeps them in a folder beside the executable or in the macOS bundle (`src/packaged.rs`). An Android
//! app has no such folder: its files are inside the APK. So for Android the stylesheets are compiled in
//! (`print_sheet::embedded`, about 0.5 MB of CSS). The table is generated for every target; only Android and tests
//! compile the module that includes it, so desktop binaries do not carry it.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("../../print-overrides");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut sheets: Vec<(String, PathBuf)> = fs::read_dir(&dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| path.extension().is_some_and(|ext| ext == "css"))
                .filter_map(|path| {
                    let slug = path.file_stem()?.to_str()?.to_owned();
                    let path = path.canonicalize().ok()?;
                    Some((slug, path))
                })
                .collect()
        })
        .unwrap_or_default();
    sheets.sort();

    let mut table = String::from(
        "/// `print-overrides/`, by slug: generated by build.rs.\npub(crate) static SHEETS: &[(&str, &str)] = &[\n",
    );
    for (slug, path) in &sheets {
        println!("cargo:rerun-if-changed={}", path.display());
        table.push_str(&format!(
            "    ({slug:?}, include_str!({:?})),\n",
            path.display().to_string()
        ));
    }
    table.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("print_overrides.rs");
    fs::write(out, table).expect("write print_overrides.rs");
}
