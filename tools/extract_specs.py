#!/usr/bin/env python3
"""Extract painted per-form field specs into app/shell/specs.js.

Reads each crates/bir-desktop/src/views/form_*_view.rs:
  - *_INPUTS / *_FIELDS const arrays of string tuples -> (key, label, kind)
  - sync_from_inputs match arms / input_text calls -> ui_key -> draft field
Emits FORM_SPECS-compatible entries keyed by catalog code.
"""
import json
import re
import pathlib

VIEWS = pathlib.Path("/home/ubuntu/repos/buwiz-forms/crates/bir-desktop/src/views")

# const NAME: &[(&str, &str, ...)] = &[ ... ];
ARRAY = re.compile(
    r"const\s+(\w+)\s*:\s*&?\[\(?&str[^)\]]*\)?\]\s*[;=]\s*&?\[(.*?)\];", re.S
)
# a tuple whose first two elements are string literals
TUPLE = re.compile(
    r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"((?:\s*,\s*(?:"(?:[^"\\]|\\.)*"|true|false))*)\s*\)'
)
ARM = re.compile(r'"([^"]+)"\s*=>\s*draft\.([A-Za-z0-9_]+)\s*=')
ASSIGN = re.compile(r'draft\.([A-Za-z0-9_]+)\s*=\s*(?:self\.)?input_text\(\s*"([^"]+)"')

FIELD_ARRAY = re.compile(r"(TEXT_INPUTS|MONEY_INPUTS|INPUTS|FIELDS)$")

# struct-style entries: Money { key: "k", label: "l", get: |d| d.path, ... }
STRUCT_ARRAY = re.compile(
    r"const\s+(\w+)\s*:\s*&\[(Money|Text|Computed|Note)\]\s*=\s*&\[(.*?)\];",
    re.S,
)
ENTRY = re.compile(
    r'(?:Money|Text|Computed|Note)\s*\{[^}]*?key\s*:\s*"((?:[^"\\]|\\.)*)"[^}]*?'
    r'label\s*:\s*"((?:[^"\\]|\\.)*)"[^}]*?(?:get\s*:\s*\|d\|\s*d\.([a-z0-9_\.]+))?[^}]*?\}',
    re.S,
)


def parse_arrays(src):
    out = []
    for name, body in ARRAY.findall(src):
        if not FIELD_ARRAY.search(name):
            continue
        kind = "money" if "MONEY" in name else "text"
        for m in TUPLE.finditer(body):
            key, label, extra = m.groups()
            extras = re.findall(r'"((?:[^"\\]|\\.)*)"', extra or "")
            k = kind
            if any(e in ("0.00", "0,00") for e in extras):
                k = "money"
            elif any(e == "0" for e in extras):
                k = "number"
            out.append((key, label, k, None))
    for name, entry_type, body in STRUCT_ARRAY.findall(src):
        if entry_type in ("Computed", "Note"):
            continue  # read-only items don't belong in the editable spec
        kind = "money" if entry_type == "Money" else "text"
        for m in ENTRY.finditer(body):
            key, label, path = m.groups()
            out.append((key, label, kind, path))
    return out


def ui_to_draft(src):
    mapping = {k: f for k, f in ARM.findall(src)}
    for draft_field, key in ASSIGN.findall(src):
        mapping[key] = draft_field
    return mapping


def period_kind(code, src):
    if "is the month" in src or re.search(r"year\s*,\s*month", src):
        return "monthly"
    if code.endswith("Q"):
        return "quarterly"
    if code.endswith("M"):
        return "monthly"
    return "annual"


specs = {}
for path in sorted(VIEWS.glob("form_*_view.rs")):
    code = path.stem.replace("form_", "").replace("_view", "").upper()
    src = path.read_text()
    fields = parse_arrays(src)
    if not fields:
        continue
    mapping = ui_to_draft(src)
    specs[code] = {
        "code": code,
        "periods": period_kind(code, src),
        "fields": [
            {
                "key": path or mapping.get(key, key),
                "label": label,
                "kind": kind,
            }
            for key, label, kind, path in fields
        ],
    }

out = "// Generated by tools/extract_specs.py from bir-desktop view files.\n"
out += "// Re-run the generator when the painted views change.\n"
out += "export const EXTRACTED_SPECS = " + json.dumps(specs, indent=2) + ";\n"
pathlib.Path("/home/ubuntu/repos/buwiz-forms/app/shell/specs.js").write_text(out)
print(f"{len(specs)} specs")
for code, spec in specs.items():
    print(f"  {code}: {len(spec['fields'])} fields ({spec['periods']})")
